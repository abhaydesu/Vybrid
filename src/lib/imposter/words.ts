export const DEFAULT_CATEGORY_IDS = imposterCategories
  .filter((c) => c.desi)
  .map((c) => c.id);

const byId = new Map(imposterCategories.map((c) => [c.id, c]));

export function imposterCategory(id: string) {
  return byId.get(id);
}

export function parseEntry(entry: string, categoryId: string): ImposterWord {
  const [word, hint = ""] = entry.split("|");
  return { word: word.trim(), hint: hint.trim(), categoryId };
}

/** Every word in the chosen categories. */
export function imposterPool(categoryIds: string[]): ImposterWord[] {
  return categoryIds.flatMap((id) => {
    const category = byId.get(id);
    return category ? category.words.map((w) => parseEntry(w, id)) : [];
  });
}
